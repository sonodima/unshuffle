// Solo player on phone, first visit; dumps cut plans from the store (dev server module import).
import { BASE, PHONE, launch, openPlayer, shot, waitScreen, waitPhase, log, problems } from './lib.mjs'
const RUN = 's'
const browser = await launch()
const p = await openPlayer(browser, 'solo', PHONE)
const st = () => p.evaluate(async () => { const m = await import('/src/game/store.ts'); const s = m.useGame.getState(); return JSON.parse(JSON.stringify({ phase: s.room?.phase, rounds: s.room?.rounds?.map((r) => r && { track: r.track.title + ' — ' + r.track.artist, segs: r.segments.map((x) => [+x.start.toFixed(3), +x.end.toFixed(3)]), bpm: r.bpm ?? r.tempo ?? null, extra: Object.keys(r) }) })) })
try {
  await p.goto(BASE); await waitScreen(p, 'home')
  await p.waitForTimeout(2200)
  await p.getByRole('button', { name: /Ho capito/ }).tap().catch(() => log('no onboarding'))
  const t0 = Date.now()
  await p.getByRole('button', { name: 'Crea stanza', exact: true }).tap()
  await waitScreen(p, 'lobby')
  log('create→lobby ms', Date.now() - t0)
  await p.waitForTimeout(800)
  await shot(p, `${RUN}-01-lobby-solo`)
  // Phone host: go to Playlist tab
  await p.getByRole('tab', { name: /Playlist/ }).tap()
  await p.waitForTimeout(800)
  await shot(p, `${RUN}-02-playlist-tab`)
  const chip = p.getByRole('button', { name: /Rap italiano/ }).first()
  await chip.scrollIntoViewIfNeeded().catch(() => {})
  await chip.tap().catch(async (e) => { log('chip tap failed', e.message) })
  const firstResult = p.locator('section[aria-label="Scegli la playlist"] ul:not([aria-hidden]) li button[aria-pressed]').first()
  await firstResult.waitFor({ state: 'visible', timeout: 20000 })
  await p.waitForTimeout(800)
  await shot(p, `${RUN}-03-chip-results`)
  await firstResult.tap()
  await p.waitForTimeout(800)
  await shot(p, `${RUN}-04-picked`)
  await p.getByRole('tab', { name: /Regole/ }).tap(); await p.waitForTimeout(600)
  await shot(p, `${RUN}-05-rules-tab`)
  const setRadio = async (group, name) => p.getByRole('radiogroup', { name: group }).first().getByRole('radio', { name }).first().tap()
  await setRadio('Round', '3')
  await p.getByRole('button', { name: /Inizia partita/ }).first().tap()
  const t1 = Date.now()
  await waitPhase(p, 'intro', 60000)
  log('start→intro ms', Date.now() - t1)
  const plans = []
  for (let r = 0; r < 3; r++) {
    await waitPhase(p, 'playing', 90000)
    await p.waitForTimeout(2000)
    const s = await st()
    plans.push(s.rounds[r])
    if (r === 0) await shot(p, `${RUN}-10-solo-playing`)
    await p.getByRole('button', { name: /^Conferma/ }).first().tap()
    const t2 = Date.now()
    await waitPhase(p, 'reveal', 20000)
    log('solo confirm→reveal ms', Date.now() - t2)
    await p.waitForTimeout(6000)
    if (r === 0) await shot(p, `${RUN}-11-solo-reveal`)
    await p.getByRole('button', { name: r === 2 ? /Classifica finale/ : /Prossimo round/ }).first().tap()
  }
  await waitScreen(p, 'final', 20000)
  await p.waitForTimeout(4000)
  await shot(p, `${RUN}-20-solo-final`)
  log('final text', (await p.evaluate(() => document.querySelector('[data-screen-frame]:not([inert])')?.innerText)).replace(/\n+/g, ' | ').slice(0, 600))
  const s = await st()
  for (const pl of s.rounds.length ? s.rounds : plans) console.log(JSON.stringify(pl))
  for (const pl of plans) console.log('PLAN', JSON.stringify(pl))
} catch (e) {
  problems.push('FATAL ' + e.stack)
  await shot(p, `${RUN}-99`).catch(() => {})
} finally {
  await browser.close()
  console.log('problems:\n' + (problems.join('\n') || '(none)'))
}
